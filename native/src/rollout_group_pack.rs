//! Canonical GroupPack-v1 framing for native rollout archives.

use crate::{
    budget::{Budget, BudgetVec, Control, sort_unstable_by},
    error::{Error, Result},
};
use serde::{Serialize, Serializer};
use sha2::{Digest, Sha256};
use std::{
    io::{self, Write},
    sync::Arc,
};

const MIB: usize = 1024 * 1024;
const MAX_INDEX: usize = 8 * MIB;
const MAX_ENTRIES: usize = 100_000;
const MAGIC: &[u8; 8] = b"GFBPACK1";
const PREFIX_BYTES: usize = 16;

#[derive(Serialize)]
struct Index<'a> {
    files: &'a [Member<'a>],
    format: &'static str,
}

// Field order is the canonical JSON key order. The index contains strings and
// integers only, so serde_json's compact UTF-8 output matches the Pack codec.
#[derive(Serialize)]
struct Member<'a> {
    kind: &'a str,
    length: usize,
    name: &'a str,
    offset: usize,
    #[serde(serialize_with = "serialize_hex")]
    sha256: [u8; 32],
    #[serde(skip)]
    data: &'a [u8],
}

fn serialize_hex<S: Serializer>(digest: &[u8; 32], s: S) -> std::result::Result<S::Ok, S::Error> {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut out = [0; 64];
    for (byte, pair) in digest.iter().zip(out.chunks_exact_mut(2)) {
        pair[0] = HEX[(byte >> 4) as usize];
        pair[1] = HEX[(byte & 15) as usize];
    }
    s.serialize_str(std::str::from_utf8(&out).expect("ASCII hex"))
}

struct Output {
    bytes: BudgetVec<u8>,
    limit: usize,
    failure: Option<Error>,
}

impl Output {
    fn new(limit: usize, budget: &Arc<Budget>) -> Self {
        Self {
            bytes: BudgetVec::new(budget),
            limit,
            failure: None,
        }
    }
}

impl Write for Output {
    fn write(&mut self, data: &[u8]) -> io::Result<usize> {
        let result = if data.len() > self.limit - self.bytes.len() {
            Err(Error::resource(
                "Rollout Pack output exceeds its byte bound",
            ))
        } else {
            self.bytes.extend_from_slice(data)
        };
        result.map(|()| data.len()).map_err(|error| {
            self.failure = Some(error);
            io::Error::other("Rollout Pack output failed")
        })
    }

    fn flush(&mut self) -> io::Result<()> {
        Ok(())
    }
}

/// Encode borrowed `(kind, name, bytes)` members from the rollout writer.
/// Names are generated by that writer or validated with `safe_name` before
/// crossing the Python boundary. The caller owns the input and codec
/// workspace. The output retains its budget lease through the handoff.
pub(crate) fn encode(
    members: &[(&str, &str, &[u8])],
    max_uncompressed_bytes: usize,
    budget: &Arc<Budget>,
    control: &Control,
) -> Result<(BudgetVec<u8>, usize)> {
    control.check()?;
    if max_uncompressed_bytes < PREFIX_BYTES || members.len() > MAX_ENTRIES {
        return Err(Error::contract("invalid Rollout Pack member or byte bound"));
    }
    let initial = max_uncompressed_bytes - PREFIX_BYTES;
    let mut payload_bytes = 0;
    let mut ordered = BudgetVec::with_capacity(budget, members.len())?;
    for &(kind, name, data) in members {
        if !matches!(
            kind,
            "journal"
                | "replay"
                | "candidates"
                | "result"
                | "http-log"
                | "simulator"
                | "diagnostic"
        ) || name.split('/').any(|part| matches!(part, "" | "." | ".."))
            || name.contains('\\')
            || name.chars().any(char::is_control)
        {
            return Err(Error::contract("unsafe Rollout Pack member kind or name"));
        }
        if data.len() > initial - payload_bytes {
            return Err(Error::resource("Rollout Pack payload exceeds byte bound"));
        }
        payload_bytes += data.len();
        ordered.push(Member {
            kind,
            length: data.len(),
            name,
            offset: 0,
            sha256: [0; 32],
            data,
        })?;
    }

    sort_unstable_by(&mut ordered, |lhs, rhs| lhs.name.cmp(rhs.name), control)?;
    let mut offset = 0;
    let mut previous = None;
    for member in ordered.iter_mut() {
        control.check()?;
        if previous == Some(member.name) {
            return Err(Error::contract("duplicate Rollout Pack member name"));
        }
        previous = Some(member.name);
        member.offset = offset;
        offset += member.length;
        let mut sha = Sha256::new();
        for block in member.data.chunks(MIB) {
            control.check()?;
            sha.update(block);
        }
        member.sha256 = sha.finalize().into();
    }

    let mut index = Output::new(MAX_INDEX.min(initial - payload_bytes), budget);
    serde_json::to_writer(
        &mut index,
        &Index {
            files: &ordered,
            format: "group-pack-v1",
        },
    )
    .map_err(|error| {
        index
            .failure
            .take()
            .unwrap_or_else(|| Error::contract(error.to_string()))
    })?;
    let raw_bytes = PREFIX_BYTES + index.bytes.len() + payload_bytes;
    let compressed_limit = max_uncompressed_bytes
        .checked_add(MIB)
        .ok_or_else(|| Error::resource("Rollout Pack compressed bound overflow"))?;
    let mut output = Output::new(compressed_limit, budget);
    let result = (|| -> Result<()> {
        control.check()?;
        let mut encoder = zstd::stream::write::Encoder::new(&mut output, 3)?;
        encoder.write_all(MAGIC)?;
        encoder.write_all(&(index.bytes.len() as u64).to_le_bytes())?;
        encoder.write_all(&index.bytes)?;
        for member in ordered.iter() {
            for block in member.data.chunks(MIB) {
                control.check()?;
                encoder.write_all(block)?;
            }
        }
        encoder.finish()?;
        control.check()
    })();
    result.map_err(|error| output.failure.take().unwrap_or(error))?;
    Ok((output.bytes, raw_bytes))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn canonical_index_and_payload_match_python_pack_bytes() {
        let budget = Budget::new(MIB);
        let control = Control::new(f64::MAX).unwrap();
        let input: [(&str, &str, &[u8]); 2] = [
            ("replay", "試合/終端.json", b"x"),
            ("journal", "a/journal.jsonl", b""),
        ];
        // Python canonical_json(member_index(sorted(members))) for these inputs.
        let expected = concat!(
            r#"{"files":[{"kind":"journal","length":0,"name":"a/journal.jsonl","offset":0,"sha256":"e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"},"#,
            r#"{"kind":"replay","length":1,"name":"試合/終端.json","offset":0,"sha256":"2d711642b726b04401627ca9fbac32f5c8530fb1903cc4db02258717921a4881"}],"format":"group-pack-v1"}"#,
        );
        let raw_size = 16 + expected.len() + 1;
        let (encoded, reported) = encode(&input, raw_size, &budget, &control).unwrap();
        let raw = zstd::stream::decode_all(&encoded[..]).unwrap();
        assert_eq!(reported, raw_size);
        assert_eq!(raw.len(), raw_size);
        assert_eq!(&raw[..8], b"GFBPACK1");
        assert_eq!(&raw[8..16], &(expected.len() as u64).to_le_bytes());
        assert_eq!(&raw[16..raw.len() - 1], expected.as_bytes());
        assert_eq!(&raw[raw.len() - 1..], b"x");
        assert_eq!(budget.used(), encoded.capacity_bytes());
        drop(encoded);
        assert_eq!(budget.used(), 0);
        assert!(encode(&input, raw_size - 1, &budget, &control).is_err());
    }

    #[test]
    fn rejects_duplicate_invalid_and_unadmitted_members() {
        let control = Control::new(f64::MAX).unwrap();
        let budget = Budget::new(MIB);
        let member = ("journal", "a/journal", b"x".as_slice());
        assert!(matches!(
            encode(&[member; 2], MIB, &budget, &control),
            Err(Error::Contract(_))
        ));
        for name in ["", "a//b", "/a", "a/..", "a\\b", "a\u{0085}b"] {
            assert!(matches!(
                encode(&[("journal", name, b"x")], MIB, &budget, &control),
                Err(Error::Contract(_))
            ));
        }
        assert!(matches!(
            encode(&[("other", "a", b"x")], MIB, &budget, &control),
            Err(Error::Contract(_))
        ));
        assert!(matches!(
            encode(&[member], MIB, &Budget::new(4), &control),
            Err(Error::ResourceLimit(_))
        ));
        control.cancel();
        assert!(matches!(
            encode(&[member], MIB, &budget, &control),
            Err(Error::Cancelled)
        ));
        assert_eq!(budget.used(), 0);
    }
}
